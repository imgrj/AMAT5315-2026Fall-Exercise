"""One weekly navigation bar, identical on every published lab page.

Each week's lab is generated by its own builder, so the `docs/*.html` pages drifted
in two ways: a page built before a new week existed never learned about it, and
three pages (8, 9, 10) used a compact short-label variant while the rest used the
long-label banner. The published site therefore looked different depending on
which week you opened.

This script is the single place where the week list lives. It replaces the whole
`<nav>` block of each target with one canonical component:

* the same 12 links in the same order, with long labels,
* the same `AMAT5315: Scientific Computing` brand and `GitHub Repo ↗` link,
* the same styling, carried *inside* the block so a page's own stylesheet (or a
  rebuilt page) cannot make it look different,
* the link to the page itself marked `active` / `aria-current="page"`.

It also rewrites the navs that live inside builders, so regenerating a lab cannot
bring the old bar back.

Run from the repository root:

    python tools/fix_week_nav.py

It is idempotent: running it twice changes nothing.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPO = "https://github.com/imgrj/AMAT5315-2026Fall-Exercise"

# (href, label) — week 2 is the repository index.
WEEKS = [
    ("week1-pi-lab.html", "Week 1: AI Agents &amp; Pi"),
    ("index.html", "Week 2: Molecular Dynamics"),
    ("week3-ising-lab.html", "Week 3: Ising Lattice Lab"),
    ("week4-fluid-lab.html", "Week 4: Fluid Dynamics Lab"),
    ("week5-seismic-lab.html", "Week 5: Seismic &amp; AD Lab"),
    ("week6-energy-lab.html", "Week 6: Energy-Based Models"),
    ("week7-diffusion-lab.html", "Week 7: Diffusion &amp; Flow Matching"),
    ("week8-language-lab.html", "Week 8: Language &amp; Transformer"),
    ("week9-inference-lab.html", "Week 9: Inference &amp; Tensor Nets"),
    ("week10-tensor-lab.html", "Week 10: Tensor RG &amp; Ising"),
    ("week11-tnsample-lab.html", "Week 11: Hard Problems &amp; Sampling"),
    ("week12-branching-lab.html", "Week 12: IP &amp; Learned Branching"),
]

NAV_CSS = (
    "nav.nav-banner{display:flex;flex-wrap:wrap;align-items:center;gap:6px 12px;"
    "padding:10px 22px;background:#0d121f;border-bottom:1px solid #1e293b;"
    "font-family:'Inter',system-ui,-apple-system,'Segoe UI',sans-serif;"
    "font-size:12.5px;line-height:1.35;color:#94a3b8}"
    "nav.nav-banner .nav-brand{color:#f1f5f9;font-weight:700;white-space:nowrap}"
    "nav.nav-banner a{color:#94a3b8;text-decoration:none;padding:4px 10px;"
    "border-radius:6px;white-space:nowrap}"
    "nav.nav-banner a:hover{color:#f1f5f9;background:rgba(255,255,255,.06)}"
    "nav.nav-banner a.active{color:#38bdf8;background:rgba(56,189,248,.12);"
    "border:1px solid rgba(56,189,248,.35);font-weight:600;padding:3px 9px}"
    "nav.nav-banner a.repo-link{margin-left:auto;color:#38bdf8;font-weight:600}"
    "@media(max-width:760px){nav.nav-banner{font-size:11.5px;gap:4px 8px;padding:8px 14px}}"
)

NAV_RE = re.compile(r"<nav\b[^>]*>.*?</nav>", re.S)
ANCHOR_RE = re.compile(r"<a\b[^>]*>.*?</a>", re.S)
HREF_RE = re.compile(r'href="([^"]+)"')


def canonical_nav(self_href: str) -> str:
    links = []
    for href, label in WEEKS:
        marker = ' class="active" aria-current="page"' if href == self_href else ""
        links.append(f'<a href="{href}"{marker}>{label}</a>')
    body = "\n  ".join(links)
    return (
        '<nav class="nav-banner" aria-label="Weekly labs">\n'
        f"  <style>{NAV_CSS}</style>\n"
        '  <span class="nav-brand">AMAT5315: Scientific Computing</span>\n'
        f"  {body}\n"
        f'  <a class="repo-link" href="{REPO}" target="_blank" rel="noopener">GitHub Repo \u2197</a>\n'
        "</nav>"
    )


TARGETS = [(path, path.name) for path in sorted((ROOT / "docs").glob("*.html"))]
TARGETS += [
    # navs that live inside builders, so a rebuild stays identical
    (ROOT / "week11" / "scripts" / "build_web_lab.py", "week11-tnsample-lab.html"),
    (ROOT / "week12" / "web" / "lab_template.html", "week12-branching-lab.html"),
]

EXPECTED_LINKS = [href for href, _ in WEEKS]


def week_links(nav: str) -> list[str]:
    found = []
    for anchor in ANCHOR_RE.finditer(nav):
        href = HREF_RE.search(anchor.group(0)).group(1)
        if href == "index.html" or re.match(r"week\d+-", href):
            found.append(href)
    return found


def main() -> int:
    changed = []
    for path, self_href in TARGETS:
        if not path.exists():
            continue
        text = path.read_text(encoding="utf-8")
        match = NAV_RE.search(text)
        if not match:
            print(f"skip {path.name}: no <nav> block")
            continue
        new_nav = canonical_nav(self_href)
        if match.group(0) == new_nav:
            continue
        path.write_text(text[: match.start()] + new_nav + text[match.end() :], encoding="utf-8")
        changed.append(str(path.relative_to(ROOT)))

    # verify: every nav is the canonical block, with the page itself active
    problems = []
    for path, self_href in TARGETS:
        if not path.exists():
            continue
        text = path.read_text(encoding="utf-8")
        match = NAV_RE.search(text)
        if not match:
            continue
        nav = match.group(0)
        if week_links(nav) != EXPECTED_LINKS:
            problems.append(f"{path.name}: week links are {week_links(nav)}")
        active = re.search(r'<a href="([^"]+)" class="active"', nav)
        if not active or active.group(1) != self_href:
            problems.append(f"{path.name}: wrong active link")
        if nav != canonical_nav(self_href):
            problems.append(f"{path.name}: nav is not the canonical block")
        if text.count("<nav") != 1:
            problems.append(f"{path.name}: more than one <nav> block")

    for name in changed:
        print(f"fixed {name}")
    if problems:
        print("\nnav verification failed:")
        for problem in problems:
            print("  " + problem)
        return 1
    print(f"\nall {len(TARGETS)} navs are the same 12-week bar")
    return 0


if __name__ == "__main__":
    sys.exit(main())
