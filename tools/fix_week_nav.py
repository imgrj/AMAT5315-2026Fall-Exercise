"""Keep the weekly navigation bar identical on every published lab page.

Each week's lab is generated by its own builder, so the `docs/*.html` pages drift:
a page built before a new week existed never learns about it, and the few pages
whose nav is written by hand fall further behind. The published site then shows a
different set of weeks depending on which page you open.

This script is the single place where the week list lives. It rewrites only the
`<nav>...</nav>` block of each target:

* the title `<span>` of the banner style is preserved,
* the trailing "GitHub Repo" / "Source" link is preserved,
* the link to the page itself keeps its `active` marker,
* every week link is replaced by the canonical, ordered list below,
* the two navs that live inside builders are fixed as well, so rebuilding a lab
  cannot drop a week again.

Run from the repository root:

    python tools/fix_week_nav.py

It is idempotent: running it twice changes nothing.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

# (href, banner label, compact label)
WEEKS = [
    ("week1-pi-lab.html", "Week 1: AI Agents &amp; Pi", "Week 1 \u00b7 \u03c0"),
    ("index.html", "Week 2: Molecular Dynamics", "Week 2 \u00b7 MD"),
    ("week3-ising-lab.html", "Week 3: Ising Lattice Lab", "Week 3 \u00b7 Ising"),
    ("week4-fluid-lab.html", "Week 4: Fluid Dynamics Lab", "Week 4 \u00b7 Fluids"),
    ("week5-seismic-lab.html", "Week 5: Seismic &amp; AD Lab", "Week 5 \u00b7 AD"),
    ("week6-energy-lab.html", "Week 6: Energy-Based Models", "Week 6 \u00b7 Energy"),
    ("week7-diffusion-lab.html", "Week 7: Diffusion &amp; Flow Matching", "Week 7 \u00b7 Diffusion"),
    ("week8-language-lab.html", "Week 8: Language &amp; Transformer", "Week 8 \u00b7 Language"),
    ("week9-inference-lab.html", "Week 9: Inference &amp; Tensor Nets", "Week 9 \u00b7 Inference"),
    ("week10-tensor-lab.html", "Week 10: Tensor RG &amp; Ising", "Week 10 \u00b7 Tensor RG"),
    ("week11-tnsample-lab.html", "Week 11: Hard Problems &amp; Sampling", "Week 11 \u00b7 Sampling"),
    ("week12-branching-lab.html", "Week 12: IP &amp; Learned Branching", "Week 12 \u00b7 IP &amp; Branching"),
]

NAV_RE = re.compile(r"<nav\b[^>]*>.*?</nav>", re.S)
ANCHOR_RE = re.compile(r"<a\b[^>]*>.*?</a>", re.S)
HREF_RE = re.compile(r'href="([^"]+)"')


def is_week(href: str) -> bool:
    return href == "index.html" or re.match(r"week\d+-", href) is not None


def rebuild(nav_html: str, self_href: str) -> str:
    open_tag = re.match(r"<nav\b[^>]*>", nav_html).group(0)
    compact = "aria-label" in open_tag
    inner = nav_html[len(open_tag) : -len("</nav>")]

    # The banner style may open with the course title in a <span>.
    prefix = ""
    rest = inner
    match = re.match(r"\s*(<span>.*?</span>)", inner, re.S)
    if match:
        prefix = match.group(1)
        rest = inner[match.end() :]

    # The last anchor that is not a week is the repository / source link.
    suffix = ""
    anchors = list(ANCHOR_RE.finditer(rest))
    if anchors:
        last = anchors[-1].group(0)
        href_match = HREF_RE.search(last)
        if href_match and not is_week(href_match.group(1)):
            suffix = last

    links = []
    for href, banner_label, compact_label in WEEKS:
        label = compact_label if compact else banner_label
        if href == self_href:
            attributes = ' class="active" aria-current="page"' if compact else ' class="active"'
        else:
            attributes = ""
        links.append(f'<a href="{href}"{attributes}>{label}</a>')

    if compact:
        return f"{open_tag}{''.join(links)}{suffix}</nav>"

    parts = ([prefix] if prefix else []) + links + ([suffix] if suffix else [])
    body = "\n  ".join(parts)
    return f"{open_tag}\n  {body}\n</nav>"


TARGETS = [(path, path.name) for path in sorted((ROOT / "docs").glob("*.html"))]
TARGETS += [
    # navs that live inside builders, so a rebuild stays correct
    (ROOT / "week11" / "scripts" / "build_web_lab.py", "week11-tnsample-lab.html"),
    (ROOT / "week12" / "web" / "lab_template.html", "week12-branching-lab.html"),
]

# The nav container is a flex row; without wrapping, the last weeks are clipped
# once the list grows past the window width (week 6 shipped without it). Only the
# three weekly-nav containers are touched, never a lightbox's button row.
NAV_RULE = re.compile(r"(?m)^[ \t]*(\.nav-banner|\.week-nav|nav)[ \t]*\{([^}]*)\}", re.S)


def ensure_wrap(text: str) -> tuple[str, int]:
    added = 0

    def fix(match: re.Match) -> str:
        nonlocal added
        body = match.group(2)
        is_flex = re.search(r"display:\s*flex\s*;", body) is not None
        if not is_flex or "flex-wrap" in body:
            return match.group(0)
        added += 1
        head = match.group(0)[: match.group(0).index("{")]
        new_body = re.sub(r"display:\s*flex\s*;", "display: flex; flex-wrap: wrap;", body, count=1)
        return f"{head}{{{new_body}}}"

    return NAV_RULE.sub(fix, text), added


def main() -> int:
    changed = []
    wrapped = []
    for path, self_href in TARGETS:
        if not path.exists():
            continue
        text = path.read_text(encoding="utf-8")
        before = text
        match = NAV_RE.search(text)
        if not match:
            print(f"skip {path.name}: no <nav> block")
            continue
        nav = match.group(0)
        new_nav = rebuild(nav, self_href)
        if new_nav != nav:
            text = text[: match.start()] + new_nav + text[match.end() :]
        text, added = ensure_wrap(text)
        if added:
            wrapped.append(f"{path.relative_to(ROOT)} ({added})")
        if text != before:
            path.write_text(text, encoding="utf-8")
            changed.append(str(path.relative_to(ROOT)))

    # verify
    problems = []
    for path, self_href in TARGETS:
        if not path.exists():
            continue
        text = path.read_text(encoding="utf-8")
        match = NAV_RE.search(text)
        if not match:
            continue
        found = [HREF_RE.search(a.group(0)).group(1)
                 for a in ANCHOR_RE.finditer(match.group(0))
                 if is_week(HREF_RE.search(a.group(0)).group(1))]
        expected = [href for href, _, _ in WEEKS]
        if found != expected:
            problems.append(f"{path.name}: {found}")
        elif self_href not in found:
            problems.append(f"{path.name}: its own page is not in the nav")
        else:
            active = re.search(r'<a href="([^"]+)" class="active"', match.group(0))
            if not active or active.group(1) != self_href:
                problems.append(f"{path.name}: wrong active link")
        for rule in NAV_RULE.finditer(text):
            body = rule.group(2)
            if re.search(r"display:\s*flex\s*;", body) and "flex-wrap" not in body:
                problems.append(f"{path.name}: nav flex row does not wrap")

    for name in changed:
        print(f"fixed {name}")
    for name in wrapped:
        print(f"wrapped {name}")
    if problems:
        print("\nnav verification failed:")
        for problem in problems:
            print("  " + problem)
        return 1
    print(f"\nall {len(TARGETS)} navs carry the same {len(WEEKS)} weeks and wrap")
    return 0


if __name__ == "__main__":
    sys.exit(main())
